#!/bin/bash
# Inside the chroot, as root. usage: chroot-desktop.sh <user> <mate|xfce|lxde>
# Installs a desktop and the start-desktop launcher (PanVK/Zink aware).
set -e
export DEBIAN_FRONTEND=noninteractive
U="$1"; DE="${2:-mate}"
apt-get update
apt-get -y install sudo locales ca-certificates dbus-x11 pulseaudio pulseaudio-utils pavucontrol \
  x11-xserver-utils xdg-utils fonts-noto fonts-noto-color-emoji adwaita-icon-theme gvfs
case "$DE" in
  mate) apt-get -y install --no-install-recommends mate-desktop-environment; SESSION=mate-session ;;
  xfce) apt-get -y install xfce4 xfce4-goodies; SESSION=startxfce4 ;;
  lxde) apt-get -y install lxde; SESSION=startlxde ;;
esac
id "$U" >/dev/null 2>&1 && usermod -aG audio,video,render "$U" || true
cat > /usr/local/bin/ld-dbus-start <<'EOS'
#!/bin/bash
mkdir -p /run/dbus
[ -s /etc/machine-id ] || dbus-uuidgen --ensure=/etc/machine-id
pgrep -x dbus-daemon >/dev/null || dbus-daemon --system --fork
EOS
cat > /usr/local/bin/start-desktop <<EOS
#!/bin/bash
MODE=\${1:-auto}; ZINK=\${2:-1}
export DISPLAY=:0 PULSE_SERVER=127.0.0.1 XDG_SESSION_TYPE=x11 GDK_BACKEND=x11 NO_AT_BRIDGE=1
export XDG_RUNTIME_DIR=/tmp/runtime-\$(id -u); mkdir -p "\$XDG_RUNTIME_DIR"; chmod 700 "\$XDG_RUNTIME_DIR"
export XDG_CURRENT_DESKTOP=$DE
[ -f /etc/gpu-vendor ] && . /etc/gpu-vendor
[ "\$MODE" = auto ] && MODE=\${GPU_VENDOR:-software}
# ICD directory is generated by gpu-setup.sh; pick the manifest for the chosen GPU
case "\$MODE" in
  mali)   export VK_ICD_FILENAMES=/usr/share/vulkan/icd.d/panfrost_icd.aarch64.json PANVK_NO_AFBC=1
          [ "\$ZINK" = 1 ] && export MESA_LOADER_DRIVER_OVERRIDE=zink GALLIUM_DRIVER=zink ;;
  adreno) export VK_ICD_FILENAMES=/usr/share/vulkan/icd.d/freedreno_icd.aarch64.json
          [ "\$ZINK" = 1 ] && export MESA_LOADER_DRIVER_OVERRIDE=zink GALLIUM_DRIVER=zink ;;
  *)      export LIBGL_ALWAYS_SOFTWARE=1 GALLIUM_DRIVER=llvmpipe ;;
esac
# audio fallback: if Termux PulseAudio is not listening, start one here
(exec 3<>/dev/tcp/127.0.0.1/4713) 2>/dev/null || pulseaudio --start --exit-idle-time=-1 \
  --load="module-native-protocol-tcp auth-ip-acl=127.0.0.1 auth-anonymous=1" 2>/dev/null
exec dbus-launch --exit-with-session $SESSION
EOS
chmod +x /usr/local/bin/start-desktop /usr/local/bin/ld-dbus-start
